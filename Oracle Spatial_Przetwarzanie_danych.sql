1D.
SELECT ID
FROM FIGURY
WHERE SDO_FILTER(KSZTALT,
        SDO_GEOMETRY(2001, NULL, SDO_POINT_TYPE(3,3,NULL), NULL, NULL)
      ) = 'TRUE';

Wynik nie odpowiada rzeczywistości (zwraca 3 figury zamiast 1). SDO_FILTER wykonuje tylko pierwszą fazę zapytania, czyli porównanie minimalnych prostokątów ograniczających (MBR) z indeksu. Nie sprawdza dokładnej geometrii.
1E.
SELECT ID
FROM FIGURY
WHERE SDO_RELATE(KSZTALT,
        SDO_GEOMETRY(2001, NULL, SDO_POINT_TYPE(3,3,NULL), NULL, NULL),
        'mask=ANYINTERACT') = 'TRUE';
Teraz wynik jest zgodny z rzeczywistością (tylko ID = 2), bo operator wykonuje też drugą fazę, czyli dokładne porównanie geometrii.

2A.
SELECT m.CITY_NAME AS MIASTO,
       SDO_NN_DISTANCE(1) AS ODL
FROM MAJOR_CITIES m
WHERE SDO_NN(m.GEOM,
             (SELECT GEOM FROM MAJOR_CITIES WHERE CITY_NAME = 'Warsaw'),
             'sdo_num_res=10 unit=km', 1) = 'TRUE'
  AND m.CITY_NAME <> 'Warsaw';

2B.
SELECT m.CITY_NAME AS MIASTO
FROM MAJOR_CITIES m
WHERE SDO_WITHIN_DISTANCE(m.GEOM,
        (SELECT GEOM FROM MAJOR_CITIES WHERE CITY_NAME = 'Warsaw'),
        'distance=100 unit=km') = 'TRUE'
  AND m.CITY_NAME <> 'Warsaw';

2C.
SELECT c.CNTRY_NAME AS KRAJ, m.CITY_NAME AS MIASTO
FROM COUNTRY_BOUNDARIES c, MAJOR_CITIES m
WHERE SDO_RELATE(m.GEOM, c.GEOM, 'mask=ANYINTERACT') = 'TRUE'
  AND c.CNTRY_NAME = 'Slovakia';

2D.
SELECT b.CNTRY_NAME AS PANSTWO,
       SDO_GEOM.SDO_DISTANCE(b.GEOM, p.GEOM, 1, 'unit=km') AS ODL
FROM COUNTRY_BOUNDARIES b, COUNTRY_BOUNDARIES p
WHERE p.CNTRY_NAME = 'Poland'
  AND b.CNTRY_NAME <> 'Poland'
  AND SDO_RELATE(b.GEOM, p.GEOM, 'mask=ANYINTERACT') <> 'TRUE';

3A.
SELECT b.CNTRY_NAME,
       SDO_GEOM.SDO_LENGTH(
         SDO_GEOM.SDO_INTERSECTION(a.GEOM, b.GEOM, 1), 1, 'unit=km') AS ODLEGLOSC
FROM COUNTRY_BOUNDARIES a, COUNTRY_BOUNDARIES b
WHERE a.CNTRY_NAME = 'Poland'
  AND b.CNTRY_NAME <> 'Poland'
  AND SDO_TOUCH(a.GEOM, b.GEOM) = 'TRUE';

