3C.
SELECT SDO_GEOM.SDO_AREA(
         SDO_GEOM.SDO_MBR(
           SDO_GEOM.SDO_UNION(a.GEOM, b.GEOM, 0.01)),
         1, 'unit=SQ_KM') AS SQ_KM
FROM MAJOR_CITIES a, MAJOR_CITIES b
WHERE a.CITY_NAME = 'Warsaw'
  AND b.CITY_NAME = 'Lodz';

