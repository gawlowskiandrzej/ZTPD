SELECT t.g.SDO_GTYPE AS GTYPE
FROM (SELECT SDO_GEOM.SDO_UNION(c.GEOM, m.GEOM, 0.01) AS g
      FROM COUNTRY_BOUNDARIES c, MAJOR_CITIES m
      WHERE c.CNTRY_NAME = 'Poland'
        AND m.CITY_NAME = 'Prague') t;

3E.
SELECT CITY_NAME, CNTRY_NAME
FROM (SELECT m.CITY_NAME, c.CNTRY_NAME,
             SDO_GEOM.SDO_DISTANCE(m.GEOM,
               SDO_GEOM.SDO_CENTROID(c.GEOM, 1), 1) AS D
      FROM MAJOR_CITIES m, COUNTRY_BOUNDARIES c
      WHERE m.CNTRY_NAME = c.CNTRY_NAME
      ORDER BY D)
WHERE ROWNUM = 1;

3F.
SELECT r.NAME,
       SUM(SDO_GEOM.SDO_LENGTH(
             SDO_GEOM.SDO_INTERSECTION(r.GEOM, c.GEOM, 1),
             1, 'unit=km')) AS DLUGOSC
FROM RIVERS r, COUNTRY_BOUNDARIES c
WHERE c.CNTRY_NAME = 'Poland'
  AND SDO_RELATE(r.GEOM, c.GEOM, 'mask=ANYINTERACT') = 'TRUE'
GROUP BY r.NAME;
