1.A
CREATE TABLE S6_LRS (GEOM SDO_GEOMETRY);

1.B
INSERT INTO S6_LRS
SELECT SR.GEOM
FROM   ZTPD.STREETS_AND_RAILROADS SR, ZTPD.MAJOR_CITIES C
WHERE  C.CITY_NAME = 'Koszalin'
AND    SDO_WITHIN_DISTANCE(SR.GEOM, C.GEOM, 'distance=10 unit=km') = 'TRUE';

COMMIT;

1.C.
SELECT SDO_GEOM.SDO_LENGTH(GEOM, 1, 'unit=km') AS DISTANCE,
       ST_LINESTRING(GEOM).ST_NUMPOINTS()      AS ST_NUMPOINTS
FROM   S6_LRS;

1.D.
UPDATE S6_LRS
SET    GEOM = SDO_LRS.CONVERT_TO_LRS_GEOM(
                  GEOM, 0, SDO_GEOM.SDO_LENGTH(GEOM, 1, 'unit=km'));
COMMIT;

1.E
INSERT INTO USER_SDO_GEOM_METADATA
VALUES ('S6_LRS', 'GEOM',
        MDSYS.SDO_DIM_ARRAY(
            MDSYS.SDO_DIM_ELEMENT('X', 12.0, 29.0, 0.01),
            MDSYS.SDO_DIM_ELEMENT('Y', 48.0, 57.0, 0.01),
            MDSYS.SDO_DIM_ELEMENT('M',  0.0, 300.0, 0.01)),
        8307);
COMMIT;

1.F
CREATE INDEX S6_LRS_IDX
ON S6_LRS(GEOM)
INDEXTYPE IS MDSYS.SPATIAL_INDEX;

2.A
SELECT SDO_LRS.VALID_MEASURE(GEOM, 500) AS VALID_500
FROM   S6_LRS;

2.B
SELECT SDO_LRS.GEOM_SEGMENT_END_PT(GEOM).SDO_ORDINATES AS END_PT
FROM   S6_LRS;

2.C
SELECT SDO_LRS.LOCATE_PT(GEOM, 150, 0).SDO_ORDINATES AS KM150
FROM   S6_LRS;

2.D
SELECT SDO_LRS.CLIP_GEOM_SEGMENT(GEOM, 120, 160).SDO_ORDINATES AS CLIPPED
FROM   S6_LRS;

2.E
SELECT SDO_GEOMETRY(3301, 8307, NULL,
                    SDO_ELEM_INFO_ARRAY(1, 1, 1),
                    SDO_ORDINATE_ARRAY(V.X, V.Y, V.Z)).SDO_ORDINATES AS WJAZD_NA_S6
FROM  (SELECT T.X, T.Y, T.Z
       FROM   S6_LRS S6, TABLE(SDO_UTIL.GETVERTICES(S6.GEOM)) T
       WHERE  T.Z > (SELECT SDO_LRS.FIND_MEASURE(S6.GEOM, C.GEOM)
                     FROM   S6_LRS S6, ZTPD.MAJOR_CITIES C
                     WHERE  C.CITY_NAME = 'Slupsk')
       ORDER BY T.Z) V
WHERE  ROWNUM = 1;

2.F
SELECT SDO_GEOM.SDO_LENGTH(
           SDO_LRS.OFFSET_GEOM_SEGMENT(
               S6.GEOM, M.DIMINFO, 50, 200, 50,
               'unit=m arc_tolerance=0.05'),
           1, 'unit=km') AS KOSZT
FROM   S6_LRS S6, USER_SDO_GEOM_METADATA M
WHERE  M.TABLE_NAME  = 'S6_LRS'
AND    M.COLUMN_NAME = 'GEOM';